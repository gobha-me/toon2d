// Regenerate the skill's single-file references from the prototype so they never drift.
// node scripts/sync-skill.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const SKILL = 'skills/toon2d-expression-rig/reference';
const strip = (src) => src.replace(/^import [^;]+;\n/gm, '');
const helpers = `// ---- inlined math helpers (no imports, so this file drops into any JS/TS project)
function clamp(v, lo, hi) {
  return v < lo ? lo : v > hi ? hi : v;
}
function lerp(a, b, t) {
  return a + (b - a) * t;
}
function smoothstep(t) {
  const x = clamp(t, 0, 1);
  return x * x * (3 - 2 * x);
}
/** Frame-rate independent exponential approach. */
function damp(current, target, rate, dt) {
  if (rate <= 0 || dt <= 0) return current;
  return lerp(current, target, 1 - Math.exp(-rate * dt));
}
`;

const face = strip(readFileSync('prototype/face.js', 'utf8'));
const director = strip(readFileSync('prototype/reactions.js', 'utf8'));
writeFileSync(
  `${SKILL}/face-core.js`,
  `// toon2d expression rig — single-file reference implementation (ES module, no deps).
// GENERATED by scripts/sync-skill.mjs from prototype/face.js + prototype/reactions.js.
// Port it line-by-line to GDScript/C#/Lua; nothing here depends on a renderer.
${helpers}
${face}
// ======================================================= expression director
${director}`,
);

const render = readFileSync('prototype/render.js', 'utf8');
const start = render.indexOf('// ---------------------------------------------------------------- face');
const end = render.indexOf('// ---------------------------------------------------------------- chains');
if (start < 0 || end < 0) throw new Error('face markers not found in render.js');
writeFileSync(
  `${SKILL}/face-render-canvas.js`,
  `// Canvas 2D placeholder face renderer (vector shapes) — reads only the flat param object.
// GENERATED by scripts/sync-skill.mjs from prototype/render.js.
// Coordinates are head-bone space: origin at the neck joint, y down, face toward +x (3/4 view).
// pal = { line, skinShade, iris, irisDark, mouth, tongue, blush }.
const TAU = Math.PI * 2;
function clamp(v, lo, hi) {
  return v < lo ? lo : v > hi ? hi : v;
}
function fillStroke(ctx, fill, line, width = 1.6) {
  ctx.fillStyle = fill;
  ctx.fill();
  ctx.lineWidth = width;
  ctx.strokeStyle = line;
  ctx.lineJoin = 'round';
  ctx.stroke();
}

${render.slice(start, end).trimEnd()}

export { drawFaceLower, drawFaceUpper, drawEye, drawMouth };
`,
);

const core = await import(`../${SKILL}/face-core.js?${Date.now()}`);
writeFileSync(
  `${SKILL}/expressions.json`,
  `${JSON.stringify({ params: core.FACE_PARAMS, expressions: core.EXPRESSIONS, reactions: core.REACTIONS }, null, 2)}\n`,
);
console.log('skill references regenerated');
